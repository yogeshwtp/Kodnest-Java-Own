public class PosNeg {
    public static void main(String[] args) {
        int num = 0;
        if (num > 0) {
            System.out.println("Positive");//25
        } else if (num < 0) {
            System.out.println("Negative");//-25
        } else {
            System.out.println("Zero");//0
        }
    }
}